//! The typed bridge. Every command and event here is exported to `src/shared/bindings.ts`.

use specta_typescript::Typescript;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands, collect_events};

use crate::commands::{self as c};
use crate::commands_registry::{COMMANDS, CommandSpec};
use crate::events::{
    CommandRun, DeepLinkOpened, DocumentsChanged, InterruptionRequested, PermissionsChanged, PreferencesChanged,
    TasksChanged, UpdateStateChanged,
};
use crate::preferences::ZOOM_LEVELS;

pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Throw)
        // Every type serializes and deserializes with the same shape.
        .disable_serde_phases()
        .commands(collect_commands![
            c::app_get_info,
            c::preferences_get,
            c::preferences_migrate_interface,
            c::preferences_update,
            c::shortcuts_set,
            c::shortcuts_reset,
            c::shortcuts_record,
            c::links_open_known_destination,
            c::window_new,
            c::window_get_session,
            c::window_set_session,
            c::window_quit,
            c::lifecycle_set_dirty_state,
            c::lifecycle_resolve_interruption,
            c::updates_get_state,
            c::updates_check,
            c::updates_restart,
            c::tasks_list,
            c::tasks_cancel,
            c::tasks_retry,
            c::tasks_dismiss,
            c::permissions_list,
            c::permissions_request,
            c::permissions_reset,
            c::deep_links_get_protocol,
            c::deep_links_ready,
            c::diagnostics_get,
            c::diagnostics_copy_report,
            c::diagnostics_open_logs,
            c::diagnostics_reload,
            c::diagnostics_reset_preferences,
            c::showcase::documents_list,
            c::showcase::documents_get,
            c::showcase::documents_create,
            c::showcase::documents_save,
            c::showcase::documents_delete,
            c::showcase::documents_open_text,
            c::showcase::documents_save_text,
            c::showcase::sharing_copy_workspace_summary,
            c::showcase::tasks_copy_digest,
            c::showcase::tasks_clear_completed,
            c::showcase::tasks_start_file_hash,
        ])
        .events(collect_events![
            PreferencesChanged,
            TasksChanged,
            PermissionsChanged,
            DocumentsChanged,
            CommandRun,
            InterruptionRequested,
            UpdateStateChanged,
            DeepLinkOpened,
        ])
        .constant("COMMAND_REGISTRY", COMMANDS.to_vec())
        .constant("ZOOM_LEVELS", ZOOM_LEVELS)
        .constant("SHOWCASE_ENABLED", crate::app_config::SHOWCASE)
        .constant("PRODUCT_NAME", crate::app_config::PRODUCT_NAME)
        .typ::<CommandSpec>()
}

/// Write the TypeScript bindings. Used by `pnpm run bindings` and the bindings check.
pub fn export(path: &std::path::Path) -> Result<(), String> {
    builder()
        .export(
            Typescript::default()
                .header("// Generated by tauri-specta from src-tauri. Run `pnpm run bindings`; do not edit.\n"),
            path,
        )
        .map_err(|error| error.to_string())
}
